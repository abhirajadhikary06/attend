_FALLBACK = '<circle cx="12" cy="12" r="9"/>'


def svg_bytes(name: str, color: str, stroke: float = 2.0) -> QByteArray:
    body = _PATHS.get(name, _FALLBACK)
    doc = (
        '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" '
        f'fill="none" stroke="{color}" stroke-width="{stroke}" '
        f'stroke-linecap="round" stroke-linejoin="round">{body}</svg>'
    )
    return QByteArray(doc.encode("utf-8"))


def icon_pixmap(name: str, color: str, size: int = 18, dpr: float = 1.0) -> QPixmap:
    px = max(1, int(size * dpr))
    pm = QPixmap(px, px)
    pm.fill(Qt.transparent)
    renderer = QSvgRenderer(svg_bytes(name, color))
    painter = QPainter(pm)
    renderer.render(painter)
    painter.end()
    pm.setDevicePixelRatio(dpr)
    return pm


def icon(name: str, color: str, size: int = 18, on_color: str | None = None) -> QIcon:
    """QIcon with a normal state and an optional checked (On) state colour."""
    ic = QIcon()
    ic.addPixmap(icon_pixmap(name, color, size, 2.0), QIcon.Normal, QIcon.Off)
    ic.addPixmap(icon_pixmap(name, on_color or color, size, 2.0), QIcon.Normal, QIcon.On)
    return ic
